//
// 全局实验开关
//
// 目的：本项目要求「同种子 + 同二进制 = 同结果」，因此每次改动都要能做 A/B 与回退。
// 为了避免每加一个开关就要改一串函数签名（main → Solver → TabuSearch → Schedule），
// 这里统一用内联全局变量承载，由 main.cpp 解析命令行后设置一次。
//
// 约定：
//   * 默认值 = 新的（更快的 / 期望更好的）行为。
//   * 每个开关都配一个命令行参数用于关闭或切回旧行为。
//

#ifndef CONFIG_H
#define CONFIG_H

#include <string>

namespace cfg
{
    // ---------------------------------------------------------------------
    // P1：top-K 探针只做正向评估
    //
    // top-K 探针每代要评估 8 个候选移动，但它只关心 makespan。
    // 原实现走完整的 update_time()（拓扑 + 正向 + 反向），其中的反向遍
    // （q_job / q_machine / backward_path_length）是给「下一轮识别关键路径、
    // 计算 LB」用的，探针阶段根本不读。
    // 打开后探针只做拓扑 + 正向松弛，makespan 数值完全一致。
    // ---------------------------------------------------------------------
    inline bool fast_probe = true;

    // ---------------------------------------------------------------------
    // P11：动态 top-K
    //
    // 固定 K=8 的问题：LB 是**估计值**，接近最优时大量候选的 LB 会打平，
    // 此时「按 LB 取前 8」只是在打平的候选里随机采样 8 个，
    // 真实的改进移动很可能恰好在被丢掉的那部分里。
    //
    // 打开后：若 LB 最小值上的打平数超过 K，就把 K 扩到覆盖全部打平候选
    // （上限 topk_max）。只在打平时才付出额外开销。
    //
    // ⚠️ 实测结论（2026-09-13，代表集 27 例 @1M）：**默认关闭**。
    // 20k 档看起来 2 例变好 0 例变差，但 1M 档变成 8 例变好 / 8 例变差、
    // 平均 gap 3.07%→3.13%（mt20_edata 恶化 +23），且慢约 18%。
    // 判定为「打平且更慢」，故默认关，保留开关供后续重测。
    // ---------------------------------------------------------------------
    inline bool adaptive_topk = false;
    inline int topk_max = 32;

    // ---------------------------------------------------------------------
    // C1：LAHC 滑动窗口接受准则
    //
    // 经典 Late Acceptance Hill Climbing（Burke et al. 2003）：维护长度为 H
    // 的「历史 cost 窗口」，每代接受「优于窗口中对应历史解」的邻域移动，
    // 允许当前解暂时劣化以逃离吸引域；同时永远接受改善移动。
    // 仅改"接受准则"、不改邻域，风险低收益高——让每次迭代选得更值钱，
    // 在同等迭代预算下达更多下界（对应"不靠堆时间、改算法"的优化方向）。
    // 默认关闭（保持与原 TS 行为一致、可 A/B 对照）。
    // ---------------------------------------------------------------------
    inline bool lahc = false;
    inline int  lahc_H = 150;

    // ---------------------------------------------------------------------
    // C3：ILS 自适应扰动强度
    //
    // 原扰动强度为线性 `1.0 + 0.15 * perturb_since_improve`（扰动越久线性增强）。
    // 改为二次自适应：早期弱扰动（精细局部搜索）、长期无改进时强扰动（大幅逃逸），
    // 更契合 ILS 思想，帮助 Dauzère 等难例与"差 1~3 单位"算例在同等迭代内收敛。
    // 默认关闭（保持与原行为一致、可 A/B）。
    // ---------------------------------------------------------------------
    inline bool adaptive_perturb = false;

    /// 返回当前所有开关的摘要，用于打印到 stdout，便于核对每次实验的配置
    inline std::string summary()
    {
        std::string s;
        s += "fast_probe=" + std::string(fast_probe ? "on" : "off");
        s += " adaptive_topk=";
        s += adaptive_topk ? ("on(max=" + std::to_string(topk_max) + ")") : "off";
        s += " lahc=";
        s += lahc ? ("on(H=" + std::to_string(lahc_H) + ")") : "off";
        s += " adaptive_perturb=";
        s += adaptive_perturb ? "on" : "off";
        return s;
    }
}

#endif
